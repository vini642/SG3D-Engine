GLYPHS={'0':0x7B6F,'1':0x2497,'2':0x73E7,'3':0x73CF,'4':0x5BC9,'5':0x79CF,'6':0x79EF,'7':0x7249,'8':0x7BEF,'9':0x7BCF,'A':0x7BED,'B':0x6BAE,'C':0x7927,'D':0x6B6E,'E':0x79E7,'F':0x79E4,'G':0x796F,'H':0x5BED,'I':0x7247,'J':0x124F,'K':0x5BAD,'L':0x4927,'M':0x5FED,'N':0x5F6D,'O':0x7B6F,'P':0x7BE4,'Q':0x7B7B,'R':0x7BAD,'S':0x79CF,'T':0x7249,'U':0x5B6F,'V':0x5B6A,'W':0x5BFD,'X':0x5AAD,'Y':0x5A49,'Z':0x72A7,':':0x0404,'.':0x0001,'!':0x2492,'-':0x01C0,'/':0x1248,'?':0x7282,'+':0x05D0,'_':0x0007}
def draw_text(pen,x,y,text,color,maxchars=27):
    for n,ch in enumerate(str(text).upper()[:maxchars]):
        bits=GLYPHS.get(ch,0)
        for yy in range(5):
            for xx in range(3):
                if bits & (1 << (14-yy*3-xx)):
                    pen.point((x+n*4+xx,y+yy),fill=color)
