def draw_native_text(draw,x,y,string,color,maxchars=27):
    for c in str(string).upper()[:maxchars]:
        if c=="\n":
            y+=9;continue
        glyph=FONT_5X7.get(c,FONT_5X7["?"])
        for yy,row in enumerate(glyph):
            for xx in range(5):
                if row&(1<<(4-xx)):draw.point((x+xx,y+yy),fill=color)
        x+=6
